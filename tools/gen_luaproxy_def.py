# -*- coding: utf-8 -*-
"""Generate a PE-forwarder .def for the optional luaJIT.dll proxy.

The host loads luaJIT.dll by name and resolves Lua 5.1 C-ABI symbols via
GetProcAddress. A same-name proxy DLL therefore only needs to keep all 323
original exports working; PE forwarders ("name = luaJIT_real.name") are handled
by the Windows loader, so no ordinal table or per-version RVA scan is needed.

Only lua_setfield is implemented locally (see src/ProxyLuaJIT.cpp).
"""
import os
import struct
import sys

ROOT = r"E:\AviUtl2脚本插件开发调试"
SEED = os.path.join(ROOT, "Codex的AviUtl2小屋", ".test",
                    "VolumetricLight3D-escalated", ".astra", "runtime",
                    "aviutl2", "luaJIT.dll")
DEF_OUT = os.path.join(ROOT, "ProxyLayer", "dist", "luaJIT.def")
REAL_NAME = "luaJIT_real"


def read_exports(path):
    with open(path, "rb") as f:
        d = f.read()
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    if d[pe:pe + 4] != b"PE\0\0":
        raise RuntimeError("not a PE file: " + path)
    coff = pe + 4
    machine, nsec, _, _, _, optsz, _ = struct.unpack_from("<HHIIIHH", d, coff)
    if machine != 0x8664:
        raise RuntimeError("expected x64 PE, got machine=0x%X" % machine)
    opt = coff + 20
    magic = struct.unpack_from("<H", d, opt)[0]
    if magic != 0x20B:
        raise RuntimeError("expected PE32+ magic")
    # DataDirectory[0] = export directory (RVA, size)
    dd = opt + 112
    exp_rva, exp_size = struct.unpack_from("<II", d, dd)
    sec = opt + optsz
    sections = []
    for i in range(nsec):
        o = sec + i * 40
        vsize, vaddr, rawsize, rawptr = struct.unpack_from("<IIII", d, o + 8)
        sections.append((vaddr, vsize, rawptr, rawsize))

    def rva2off(rva):
        for va, vs, rp, rs in sections:
            if va <= rva < va + max(vs, rs):
                return rp + (rva - va)
        raise RuntimeError("unmapped RVA 0x%X" % rva)

    eo = rva2off(exp_rva)
    nfunc, nname = struct.unpack_from("<II", d, eo + 20)
    names_rva = struct.unpack_from("<I", d, eo + 32)[0]
    no = rva2off(names_rva)
    names = []
    for i in range(nname):
        nr = struct.unpack_from("<I", d, no + 4 * i)[0]
        o = rva2off(nr)
        end = d.index(b"\0", o)
        names.append(d[o:end].decode("ascii"))
    return names, nfunc


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else SEED
    dst = sys.argv[2] if len(sys.argv) > 2 else DEF_OUT
    names, nfunc = read_exports(src)
    if nfunc != len(names):
        raise RuntimeError("ordinal-only exports present (%d funcs / %d names); "
                           "a forwarder-only .def cannot preserve ordinals"
                           % (nfunc, len(names)))
    hooked = "lua_setfield"
    if hooked not in names:
        raise RuntimeError("lua_setfield missing from export table")

    lines = [
        "; Generated by host-test/gen_luaproxy_def.py -- DO NOT EDIT BY HAND.",
        "; Source DLL: " + os.path.basename(src) + " (host runtime seed)",
        "LIBRARY luaJIT",
        "EXPORTS",
    ]
    for n in names:
        if n == hooked:
            lines.append("    " + n + "   ; local wrapper in ProxyLuaJIT.cpp")
        else:
            lines.append("    %s = %s.%s" % (n, REAL_NAME, n))
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")

    # MSVC's LINK insists on resolving the symbol AFTER the dot even when it
    # emits a PE forwarder. A matching import lib satisfies that check without
    # adding any real import to the proxy (the forwarder stays in the EAT).
    real_def = os.path.join(os.path.dirname(dst), "luaJIT_real.def")
    real_lines = ["LIBRARY luaJIT_real.dll", "EXPORTS"] + \
                 ["    " + n for n in names if n != hooked]
    with open(real_def, "w", encoding="ascii", newline="\r\n") as f:
        f.write("\n".join(real_lines) + "\n")

    print("exports: %d  forwarded: %d  hooked: %s" %
          (len(names), len(names) - 1, hooked))
    print("def:", dst)
    print("import lib def:", real_def)


if __name__ == "__main__":
    main()
